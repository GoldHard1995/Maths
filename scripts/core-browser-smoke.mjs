const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser=await chromium.launch({headless:true,channel: process.env.PLAYWRIGHT_BROWSER_CHANNEL || 'chrome'});
const output = process.env.CORE_QA_OUTPUT || '/tmp/maths-core-ui';
const origin = process.env.CORE_PREVIEW_URL || 'http://127.0.0.1:8766';
await fs.mkdir(output,{recursive:true});
for(const world of ['directed-number','algebra','linear-equation','polynomial','numerical-estimation','coordinate','percentage','identity']){
 const context=await browser.newContext({viewport:{width:1024,height:768}}),page=await context.newPage();
 const errors=[],posts=[];
 await context.route('**/*', route => route.request().method() === 'POST' ? route.abort() : route.continue());
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(r.method()==='POST' && (new URLSearchParams(r.postData() || '').has('submissionId')))posts.push(r.url())});
 await page.clock.install();
 const url=`${origin}/${world}/?schoolYear=2026-27&className=1A&studentNo=1`;
 await page.goto(url,{waitUntil:'domcontentloaded'});
 await page.locator('.game-card').first().click();
 await page.locator('.game-panel').waitFor();
 const first=await page.evaluate(()=>Object.entries(sessionStorage).filter(([k])=>k.includes('previous')));
 assert.equal(first.length,1,world+' saved round');
 await page.reload({waitUntil:'domcontentloaded'});await page.locator('.game-card').first().click();
 const second=await page.evaluate(()=>Object.entries(sessionStorage).filter(([k])=>k.includes('previous')));
 assert.equal(second.length,1);assert.equal(first[0][0],second[0][0]);assert.notEqual(first[0][1],second[0][1]);
 if(world==='numerical-estimation')assert.match(await page.locator('.round-top').innerText(),/8 基礎 · 7 核心 · 不可放棄/);
 assert.equal(await page.evaluate(()=>document.body.scrollWidth>innerWidth),false,world+' overflow');
 await page.clock.fastForward(3601000);
 await page.getByRole('heading',{name:'遊戲時間已結束'}).waitFor();
 assert.equal(posts.length,0,world+' timeout must not upload');
 assert.match(await page.locator('.finish').innerText(),/不會上傳排行榜/);
 assert.equal(await page.locator('.finish form').count(),0);
 assert.equal(await page.getByRole('button',{name:'再玩一次',exact:true}).isEnabled(),true);
 await page.screenshot({path:`${output}/${world}-timeout.png`,fullPage:true});
 await page.getByRole('button',{name:'再玩一次',exact:true}).click();
 await page.locator('.round-top').waitFor();
 assert.deepEqual(errors,[]);
 console.log(world+': reload history, timeout, no upload, replay and layout OK');
 await context.close();
}
await browser.close();
